#: 上确界可达：c 恒 1 ⇒ x 恒 1 ⇒ e_n = 1 - γⁿ ⇒ sup = 1.0。        ∎
#:
#: ⚠️ **EMA 只逼近不达到**（γⁿ > 0 恒成立）⇒ **任何阈值都必须严格小于 1.0**。
