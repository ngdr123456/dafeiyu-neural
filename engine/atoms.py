"""第 2 步：把书里命名的理论物质组织成「观念原子」

═══════════════════════════════════════════════════════════════════════════
⚠️ 性质声明（必须先读，否则会误以为这是"整理书里的清单"）

书里**没有**记分类别的清单。原文明说的是手册的三代形态（样本手册→分类手册→
合理分类手册）与**编制方法**，只给出**一个**类别名作例子：
    「为生活感到忧虑，为未来感到忧虑（含糊不清，一般化）」（[p270]）

所以本文件做的是：
  · **材料**取自书里**被命名的理论物质**（如"现实的构念""括约肌道德""以侵犯者自居"）
  · **组织方式**按书里的方法（按内容分、可拆可合、带限定语）
  · **但"按内容重新归类"这一步是本文作者做的，书里是按水平归的**

因此它的合理性不能靠引用原文来证明，只能靠**效果**检验 ——
见 tests/test_atoms.py 里的检验：组织方式必须能复现书里对同一句话的读法差异。
═══════════════════════════════════════════════════════════════════════════

原子 = 一个有具体心理内容的单元，带：
  id      短名
  text    书里的原始措辞（逐字，OCR 噪声已标注）
  source  出处 [pN]
  domain  内容域（**我的重新组织**，不是书里的水平分组）
  marks   它作为"可观察线索"时，能由什么字面特征认出来
  limits  限定语 —— 手册的类别名带括号限定，这一项对应它
"""
