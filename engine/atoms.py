def load() -> dict:
    return {"domains": DOMAINS,
            "atoms": [_atom_dict(a) for a in ATOMS],
            "reading_tests": READING_TESTS,
            "usage": (
                "本文件由 engine/atoms.py 生成，不要手改。"
                "改词表请改 engine/atoms.py 里的 Lexicon，然后重跑：python engine\\atoms.py"
            )}


def _atom_dict(a: Atom) -> dict:
    d = asdict(a)
    return d


def main() -> int:
    print("═" * 78)
    print("  观念原子表（第 2 步：按内容重新组织）")
    print("═" * 78)
    by_dom = {}
    for a in ATOMS:
        by_dom.setdefault(a.domain, []).append(a)
    for dom, name in DOMAINS.items():
        items = by_dom.get(dom, [])
        if not items:
            continue
        print()
        print("  ── %s（%s）%d 个" % (name, dom, len(items)))
        for a in items:
            print("     %-26s %s" % (a.id, a.text[:52]))
