# ---------------------------------------------------------------------------
# 原子表。每一条都必须能回答：**书里哪句话给了它名字？**
# 拿不出出处的，不许进这张表。
#
# ★ 识别词表（lexicon）的设计纪律 —— 照 rules/markers.json 那套，一条不少：
#     triggers  触发线索（字面）
#     anchors   更具体、更可靠的线索；命中任一即算强证据
#     counterexamples  反例：出现这些语境时**不算**
#     immune    否定免疫：这些短语自身就是指标，不该被否定窗口滤掉
#     basis     每条线索的来源。只能填两种：
#                 「原书」= 该书里真的用了这个措辞
#                 「层」  = 来自 markers.json 已有的、有依据的标记词表
#               凡是我为了让测试过而凑的，必须写「ENG」并说明
# ---------------------------------------------------------------------------
@dataclass
class Lexicon:
    triggers: list[str] = field(default_factory=list)
    anchors: list[str] = field(default_factory=list)
    counterexamples: list[str] = field(default_factory=list)
    immune: list[str] = field(default_factory=list)
    basis: str = ""
    # 词表自身的说明（例如"某个词为什么被移出"）—— 体检抓到问题时留痕用
    _note: str = ""
    # ★ 共现约束（E5 补）：与 triggers **同下标**，空列表 = 该条无需共现。
    #   非空时，该触发词必须与其中至少一个词**同句出现**才算命中。
    #
    #   为什么需要这个机制（而不是直接删词）：
    #     有些词有原书出处、语料里也有期望用例（删了会破坏一条有据的判据），
    #     但它单独出现时是**日常高频词**，会把不相干的句子全捞进来。
    #     「我认为」正是如此：原书 p56 拿它做例子，但「我认为可以」只是观点陈述。
    #   共现约束把"这个词"与"这个词在这种语境里"分开 —— 保住召回，去掉误伤。
    requires_any: list[list[str]] = field(default_factory=list)


@dataclass
class Atom:
    id: str
    text: str            # 书里的措辞（逐字）
    source: str          # 出处
    domain: str
    marks: list[str] = field(default_factory=list)   # 旧字段，保留兼容
    limits: str = ""     # 限定语（手册的类别名带括号限定）
    note: str = ""
    lex: Lexicon = field(default_factory=Lexicon)


