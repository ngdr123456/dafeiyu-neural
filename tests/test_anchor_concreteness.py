# -*- coding: utf-8 -*-
"""B1-B8：锚点抽取的**具体性**（2026-10-28，改动 ① 的延伸）。

★ 病灶（实测）：`_pick_anchor("丙项目资料放在北楼三层。")` 抽出 **「项目」** ——
  `_ANCHOR_THING` 里有"项目"，而"北楼三层"这类"地点＋楼层"词表里根本没有；
  且原来的优先级 thing 在 place 之前 ⇒ 抽象词压过具体物。
  ⇒ 她拿着"项目"去追问，真正具体的"北楼三层"丢了。

★ 改法：各类内部仍取最长；再**跨类比长度**，最长的赢，长度打平按既有优先级。
  这与代码里原来那句"引用对方的话必须一字不改、能引多全就引多全"一致。

★ 判据（先写）：
  B1 「北楼三层」这类地点+楼层能被抽出，且逐字出现在原话里
  B2 ★ 具体物胜过抽象词（"北楼三层" 胜过 "项目"）
  B3 既有优先级不被破坏：时间词仍优先（"那天她把我送到楼下" 取"那天"）
  B4 人称词仍优先（"我妈只问了一句" 取"我妈"）
  B5 抽象物仍能用（"我那工作干了八年" 取"工作"）
  B6 单字碎片守卫仍有效（"毛病"不切"病"）
  B7 ★ 抽出的锚点必须逐字出现在原话里（不编）
  B8 空话不硬凑锚点
"""
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.environ.get("EGO_ROOT") or os.path.dirname(_HERE)
sys.path[:0] = [str(_ROOT), str(_ROOT + "/engine")]

from respond import Responder  # noqa: E402

OK = 0
FAIL = 0


def case(name, cond, why=""):
    global OK, FAIL
    if cond:
        OK += 1
        print("  [PASS] 【%s】" % name)
    else:
        FAIL += 1
        print("  [FAIL] 【%s】%s" % (name, why))


def anchor(raw):
    return Responder()._pick_anchor(raw)[1]


print("=" * 78)
print("  锚点抽取的具体性（B1-B8）")
print("=" * 78)

# B1 / B2 ★ 具体物胜过抽象词
a = anchor("丙项目资料放在北楼三层。")
case("B1 「北楼三层」能被抽出，且逐字在原话里",
     a == "北楼三层" and a in "丙项目资料放在北楼三层。", "anchor=%r" % a)
case("B2 ★ 具体物胜过抽象词（不是「项目」）", a != "项目", "anchor=%r" % a)

# B3 时间词仍优先（长度打平时）
case("B3 时间词仍优先（那天她把我送到楼下 → 那天）",
     anchor("那天她把我送到楼下，风挺凉的。") == "那天",
     repr(anchor("那天她把我送到楼下，风挺凉的。")))

# B4 人称词仍优先
case("B4 人称词仍优先（我妈… → 我妈）",
     anchor("我妈只问了一句第一是谁。") == "我妈",
     repr(anchor("我妈只问了一句第一是谁。")))

# B5 抽象物仍能用
case("B5 抽象物仍能用（我那工作干了八年 → 工作）",
     anchor("我那工作干了八年。") == "工作",
     repr(anchor("我那工作干了八年。")))

# B6 单字碎片守卫
case("B6 单字碎片守卫仍有效（毛病不切病）",
     anchor("你说我这是不是有点毛病啊。") != "病",
     repr(anchor("你说我这是不是有点毛病啊。")))

# B7 ★ 逐字
bad = None
for t in ("丙项目资料放在北楼三层。", "更正：丙项目资料放在南楼二层。",
          "那天她把我送到楼下，风挺凉的。", "我妈只问了一句第一是谁。",
          "我那工作干了八年。", "抽屉最下层压着几张单子。"):
    a = anchor(t)
    if a and a not in t:
        bad = (t, a)
        break
case("B7 ★ 抽出的锚点必须逐字出现在原话里", bad is None, str(bad))

# B8 空话不硬凑
case("B8 空话不硬凑锚点（嗯。）", anchor("嗯。") == "", repr(anchor("嗯。")))

# B9 ★ 人 vs 地点：**人优先**（第三版的裁决）
#   ⚠️ 第二版这里断言"地点赢"，那是错的 —— 依据是 [M] 体验途径的核心是"遇到某人"，
#      日常倾诉里 person 高于 place；汉语里至亲只有 1-2 字，地点天然 4-5 字，
#      按字数跨类比 ⇒ 2 字的"我妈"永远赢不了 4 字的"南楼三层"。
_a9 = anchor("我妈的公司在南楼三层。")
case("B9 ★ 人和地点同时出现时，人优先", _a9 == "我妈", repr(_a9))

# B10 ★ 唯一的例外：显式空间安置句（含"放在/搁在/搬到"）⇒ 地点优先
_a10 = anchor("丙项目资料放在北楼三层。")
case("B10 ★ 显式空间安置句 ⇒ 地点优先（北楼三层）",
     _a10 == "北楼三层", repr(_a10))

# B11 ★「他妈」不许被抽成人物（实测 eval.jsonl 第 115 行踩过）
case("B11 ★ 粗口「我他妈」不许抽成人物",
     anchor("我他妈真受不了") == "", repr(anchor("我他妈真受不了")))

# B12 ★ 时间词不许拼代词（实测会抽出「我昨天」「你刚才」）
case("B12 ★ 时间词不拼代词（我以前 → 以前）",
     anchor("我以前那股劲儿没了。") == "以前", repr(anchor("我以前那股劲儿没了。")))

# B13 ★ 残词守卫：真实语料里的那些车祸点
for _t, _bad in (("那杯咖啡我续了三次，凉了也喝完了……钥匙搁门口垫子底下。", "匙搁门口"),
                 ("就比如昨天吧……屋里静得能听见冰箱嗡嗡响。", "见冰箱"),
                 ("我知道，我知道……就是昨天晚上收拾抽屉，又翻到那张照片了。", "拾抽屉"),
                 ("搬那台打印机", "搬那台"),
                 ("念别人台词似的", "别人台")):
    _a = anchor(_t)
    if _a == _bad:
        case("B13 ★ 残词守卫（%s）" % _bad, False, "抽出了残词 %r" % _a)
        break
else:
    case("B13 ★ 残词守卫（5 个真实车祸点全部不出现）", True)

print("-" * 78)
print("结果: %d 通过 / %d 失败 / 共 %d" % (OK, FAIL, OK + FAIL))
print()
print("MUTATION 表")
print("  MUT-A 跨比退回『按类别顺序取第一个』 → B1、B2")
print("  MUT-B 删掉地点模式                     → B1")
print("  MUT-C 优先级顺序改成 thing 在前         → B3")
sys.exit(1 if FAIL else 0)
